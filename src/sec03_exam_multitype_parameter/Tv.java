package sec03_exam_multitype_parameter;

public class Tv {

    private int year;
    private int month;

    public Tv() {
    }

    public Tv(int month, int year) {
        this.month = month;
        this.year = year;
    }

    public int getMonth() {
        return month;
    }

    public int getYear() {
        return year;
    }

    public void setMonth(int month) {
        this.month = month;
    }

    public void setYear(int year) {
        this.year = year;
    }
}
